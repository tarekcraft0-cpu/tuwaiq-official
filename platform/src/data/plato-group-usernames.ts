/** نص يوزر للبحث: يحذف الإيموجي والرموز ويبقى الحروف/الأرقام/_ */
export function usernameSearchKey(username: string) {
  return username
    .normalize("NFKD")
    .replace(/[^\p{L}\p{N}_]/gu, "")
    .toLowerCase();
}

export function usernameMatchesQuery(username: string, query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  const full = username.toLowerCase();
  if (full.includes(q)) return true;
  const key = usernameSearchKey(username);
  const qKey = usernameSearchKey(q);
  if (!qKey) return full.includes(q);
  return key.includes(qKey) || key.startsWith(qKey);
}
